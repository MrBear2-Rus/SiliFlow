//  源码里到处是中文窄字符串字面量，而本工程是用 /utf-8 编译的，
//  也就是说这些字面量在内存里是 UTF-8 字节。
//
//  wxWidgets 默认用「当前区域编码」（简体中文 Windows 上是 CP936/GBK）
//  去解释 const char*，UTF-8 的中文会被解成空串，然后 wxString::Format
//  会发现占位符和实参数量对不上，直接触发断言崩溃。
//
//  所以启动最早期要把默认窄字符转换改成 UTF-8。
// =============================================================================

